-- =====================================================================
-- 04_create_dimensions.sql  -  ANALYTICS layer: dimension tables
-- dim_date / dim_product / dim_customer / dim_seller  <- Olist (historical)
-- dim_supplier / dim_warehouse / bridge_product_supplier <- SIMULATED
--   (Olist has no supplier or warehouse data; see src/simulation/*)
-- =====================================================================
CREATE SCHEMA IF NOT EXISTS analytics;

CREATE TABLE IF NOT EXISTS analytics.dim_date (
    date_key     INTEGER PRIMARY KEY,          -- YYYYMMDD
    full_date    DATE    NOT NULL UNIQUE,
    year         SMALLINT NOT NULL,
    quarter      SMALLINT NOT NULL,
    month        SMALLINT NOT NULL,
    month_name   TEXT    NOT NULL,
    year_month   TEXT    NOT NULL,             -- 'YYYY-MM'
    iso_week     SMALLINT NOT NULL,
    day_of_month SMALLINT NOT NULL,
    day_of_week  SMALLINT NOT NULL,            -- 1=Monday .. 7=Sunday (ISO)
    day_name     TEXT    NOT NULL,
    is_weekend   BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS analytics.dim_product (
    product_id            TEXT PRIMARY KEY,
    category_name_pt      TEXT NOT NULL,
    category_name_en      TEXT NOT NULL,
    is_category_missing   BOOLEAN NOT NULL,
    name_length           NUMERIC,
    description_length    NUMERIC,
    photos_qty            NUMERIC,
    weight_g              NUMERIC,
    length_cm             NUMERIC,
    height_cm             NUMERIC,
    width_cm              NUMERIC,
    volume_cm3            NUMERIC,
    avg_unit_price        NUMERIC(12,2),       -- mean of valid historical item prices (proxy)
    units_sold_total      INTEGER NOT NULL DEFAULT 0,
    first_sale_date       DATE,
    last_sale_date        DATE,
    updated_at            TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE TABLE IF NOT EXISTS analytics.dim_customer (
    customer_id        TEXT PRIMARY KEY,       -- one per ORDER in Olist
    customer_unique_id TEXT NOT NULL,          -- the real person; use for repeat-customer KPIs
    zip_code_prefix    CHAR(5),
    city               TEXT,
    state              CHAR(2),
    latitude           DOUBLE PRECISION,
    longitude          DOUBLE PRECISION,
    updated_at         TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE TABLE IF NOT EXISTS analytics.dim_seller (
    seller_id       TEXT PRIMARY KEY,
    zip_code_prefix CHAR(5),
    city            TEXT,
    state           CHAR(2),
    latitude        DOUBLE PRECISION,
    longitude       DOUBLE PRECISION,
    updated_at      TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

-- ------------------------- SIMULATED ---------------------------------
CREATE TABLE IF NOT EXISTS analytics.dim_supplier (
    supplier_id                     TEXT PRIMARY KEY,           -- e.g. SUP-001
    supplier_name                   TEXT NOT NULL,              -- fictional name
    supplier_location               TEXT NOT NULL,
    supplier_state                  CHAR(2) NOT NULL,
    average_lead_time_days          NUMERIC(6,2) NOT NULL,      -- contractual / planned
    lead_time_std_days              NUMERIC(6,2) NOT NULL,
    actual_simulated_lead_time_days NUMERIC(6,2),               -- mean of received simulated POs
    supplier_reliability_score      NUMERIC(5,4),               -- share of POs received on time (0-1)
    supplier_status                 TEXT NOT NULL CHECK (supplier_status IN ('ACTIVE','ON_WATCH','SUSPENDED')),
    is_simulated                    BOOLEAN NOT NULL DEFAULT TRUE,
    data_source                     TEXT NOT NULL DEFAULT 'SIMULATED',
    created_at                      TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at                      TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
COMMENT ON TABLE analytics.dim_supplier IS 'SIMULATED suppliers - not Olist data. Generated by src/simulation/supplier_simulator.py';

CREATE TABLE IF NOT EXISTS analytics.dim_warehouse (
    warehouse_id   TEXT PRIMARY KEY,                           -- e.g. WH-SP
    warehouse_name TEXT NOT NULL,
    city           TEXT NOT NULL,
    state          CHAR(2) NOT NULL,
    capacity_units INTEGER NOT NULL,
    is_simulated   BOOLEAN NOT NULL DEFAULT TRUE,
    data_source    TEXT NOT NULL DEFAULT 'SIMULATED'
);
COMMENT ON TABLE analytics.dim_warehouse IS 'SIMULATED warehouses - not Olist data';

CREATE TABLE IF NOT EXISTS analytics.bridge_product_supplier (
    product_id       TEXT PRIMARY KEY REFERENCES analytics.dim_product(product_id),
    supplier_id      TEXT NOT NULL REFERENCES analytics.dim_supplier(supplier_id),
    warehouse_id     TEXT NOT NULL REFERENCES analytics.dim_warehouse(warehouse_id),
    unit_cost_proxy  NUMERIC(12,2) NOT NULL,   -- SIMULATED: avg historical price x cost ratio
    is_simulated     BOOLEAN NOT NULL DEFAULT TRUE
);
COMMENT ON TABLE analytics.bridge_product_supplier IS 'SIMULATED product -> supplier/warehouse assignment for the simulated SKU set';
